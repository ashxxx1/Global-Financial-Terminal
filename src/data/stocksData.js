function genSparkline(base, trend, volatility = 0.01) {
  const pts = [];
  let v = base;
  for (let i = 0; i < 20; i++) {
    v = v * (1 + trend / 20 + (Math.random() - 0.5) * volatility);
    pts.push(Math.round(v * 100) / 100);
  }
  return pts;
}

