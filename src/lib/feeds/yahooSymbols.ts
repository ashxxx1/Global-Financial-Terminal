/** The Yahoo symbol for one of our tickers, if it has a verified local listing. */
export const yahooFor = (ticker: string, country?: string | null): { y: string; cur: string } | undefined =>
  country ? YAHOO_SYMBOLS[`${country}:${ticker}`] : undefined;

/** Put a quoted price into the major currency unit the terminal displays. */
export const toMajorUnit = (price: number, currency: string): number =>
  price / (SUBUNIT_DIVISOR[currency] ?? 1);

/** Every verified symbol, for the sweep. */
export const ALL_YAHOO_ENTRIES: { key: string; y: string; cur: string }[] =
  Object.entries(YAHOO_SYMBOLS).map(([key, v]) => ({ key: key.split(":")[1], y: v.y, cur: v.cur }));
